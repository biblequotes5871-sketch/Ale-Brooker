let currentLang = localStorage.getItem('ale_lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('ale_lang', lang);
  const el = document.getElementById('currentLang');
  if (el) el.textContent = lang === 'en' ? 'EN' : 'አማ';
  document.documentElement.lang = lang;
  applyTranslations();
  const menu = document.getElementById('langMenu');
  if (menu) menu.classList.add('hidden');
}

function t(key) {
  return translations[currentLang][key] || translations['en'][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang] && translations[currentLang][key]) {
      el.textContent = translations[currentLang][key];
    }
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const langBtn = document.getElementById('langBtn');
  const langMenu = document.getElementById('langMenu');
  if (langBtn && langMenu) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langMenu.classList.toggle('hidden');
    });
    document.addEventListener('click', () => langMenu.classList.add('hidden'));
  }
  const cur = document.getElementById('currentLang');
  if (cur) cur.textContent = currentLang === 'en' ? 'EN' : 'አማ';
  document.documentElement.lang = currentLang;
  applyTranslations();
});
